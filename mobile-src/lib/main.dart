import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';

import 'config/app_config.dart';
import 'core/app_prefs.dart';
import 'core/auth_service.dart';
import 'core/idle_watcher.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'screens/auth_gate.dart';
import 'ui/awa_theme.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const AwaApp());
}

class AwaApp extends StatelessWidget {
  const AwaApp({super.key});

  @override
  Widget build(BuildContext context) {
    // Rebuilds when the person changes text size / display settings in Settings
    return ValueListenableBuilder<Map<String, dynamic>>(
      valueListenable: AppPrefs.notifier,
      builder: (context, prefs, _) {
        final factor = AppPrefs.textFactor(prefs);
        return MaterialApp(
          title: AppConfig.appName,
          theme: AwaTheme.build(Brightness.light, prefs),
          darkTheme: AwaTheme.build(Brightness.dark, prefs),
          themeMode: prefs['dark'] == true ? ThemeMode.dark : ThemeMode.light,
          builder: (context, child) {
            // Multiply on top of the phone's own text-size setting
            final mq = MediaQuery.of(context);
            final system = mq.textScaler.scale(1.0);
            final scaled = MediaQuery(
              data: mq.copyWith(
                textScaler: TextScaler.linear(system * factor),
                disableAnimations: prefs['reduceMotion'] == true,
              ),
              child: child!,
            );
            // Idle auto-logout lives above the Navigator, so it also covers
            // pushed screens (wallet, check-in, ...), not just the home page.
            return StreamBuilder<User?>(
              stream: AuthService.userChanges,
              builder: (context, snap) {
                if (snap.data == null) return scaled;
                return IdleWatcher(
                  timeout: const Duration(minutes: AppConfig.idleLogoutMinutes),
                  onIdle: AuthService.signOut,
                  child: scaled,
                );
              },
            );
          },
          home: const AuthGate(),
        );
      },
    );
  }
}
